//! EG4/I12 facade-export coverage across the complete dev corpus.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

fn is_live_program(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    let Some(stem) = name.strip_suffix(".ts") else {
        return false;
    };
    let bytes = stem.as_bytes();
    bytes.len() >= 5
        && bytes[0] == b'x'
        && bytes[1].is_ascii_digit()
        && bytes[2].is_ascii_digit()
        && bytes[3] == b'-'
        && bytes[4..]
            .iter()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || *byte == b'-')
}

fn live_programs(root: &Path) -> Vec<PathBuf> {
    let mut programs = std::fs::read_dir(root.join("programs"))
        .expect("read programs directory")
        .map(|entry| entry.expect("read programs entry").path())
        .filter(|path| is_live_program(path))
        .collect::<Vec<_>>();
    programs.sort();
    programs
}

fn render_coverage(total: usize, reached: usize, unreached: &BTreeSet<String>) -> String {
    let mut markdown = format!(
        "# Facade export coverage\n\nGenerated by the EG4 harness test from every `a`, `b`, and `x` program's dev run.\n\n- Total exports: {total}\n- Reached exports: {reached}\n- Unreached exports: {}\n\n## Unreached exports\n\n",
        unreached.len(),
    );
    if unreached.is_empty() {
        markdown.push_str("None.\n");
    } else {
        for name in unreached {
            markdown.push_str(&format!("- `{name}`\n"));
        }
    }
    markdown
}

#[test]
fn dev_corpus_matches_committed_facade_coverage() {
    if !crate::differential::backend_is_available() {
        return;
    }
    let _suite = crate::differential::suite_lock();
    let root = crate::repository_root();
    let mut reached = crate::differential::first_outputs()
        .iter()
        .flat_map(|output| output.coverage().iter().cloned())
        .collect::<BTreeSet<_>>();
    let live_programs = live_programs(&root);
    assert!(
        !live_programs.is_empty(),
        "live coverage program list is empty"
    );
    for program in live_programs {
        let (_, coverage) = crate::differential::run_dev_with_coverage(&program);
        reached.extend(coverage);
    }
    let all = subscript_typegpu_harness::native_symbols_generated::facade_export_names()
        .iter()
        .map(|name| (*name).to_owned())
        .collect::<BTreeSet<_>>();
    assert!(
        reached.is_subset(&all),
        "coverage reported an unknown export"
    );
    let unreached = all.difference(&reached).cloned().collect::<BTreeSet<_>>();
    let markdown = render_coverage(all.len(), reached.len(), &unreached);
    let path = root.join("specs/tracking/coverage.md");
    let committed = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    if committed != markdown {
        if std::env::var("UPDATE_COVERAGE").as_deref() == Ok("1") {
            std::fs::write(&path, &markdown)
                .unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
        } else {
            panic!(
                "{} differs; run the gate with UPDATE_COVERAGE=1 to regenerate coverage.md",
                path.display(),
            );
        }
    }
    assert!(
        unreached.is_empty(),
        "unreached facade exports:\n{}",
        unreached.iter().cloned().collect::<Vec<_>>().join("\n"),
    );
}
